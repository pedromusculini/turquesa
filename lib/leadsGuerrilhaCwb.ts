export function isCelular41(tel: string): boolean {
  return /^55419\d{8}$/.test(tel);
}

export function buildMensagemCwb(lead: LeadCwb): string {
  const local = lead.bairro?.trim()
    ? `${lead.bairro}, ${lead.cidade}`
    : lead.cidade || 'Curitiba';
  return `Oi! Tudo bem? Vi o ${lead.nome} aqui em ${local} e imaginei que a rotina de vocês ainda passa muito pelo WhatsApp.

Três dores que mais ouço de salão/barbearia na região:
1) agenda misturada no Zap → horário perdido e vácuo respondendo
2) cliente não marca sozinho → você para o atendimento pra remarcar
3) app caro ou com cartão / cliente que não baixa nada

Criei o Turquesa Agenda pra isso: a cliente autoagenda, cai no Google Calendar, e o WhatsApp continua no fluxo (sem bot caro).

Posso liberar 30 dias grátis, sem cartão e sem compromisso. Se quiser, te ajudo a configurar (sou de Curitiba).

https://www.turquesaagenda.com.br

Se não fizer sentido agora, sem problema 🙂`;
}

export function whatsappUrl(lead: LeadCwb, mensagem?: string): string {
  const text = encodeURIComponent(mensagem ?? buildMensagemCwb(lead));
  return `https://wa.me/${lead.telefone}?text=${text}`;
}
